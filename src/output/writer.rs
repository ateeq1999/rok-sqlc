use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};

const GENERATED_MARKER: &str = "// @generated by rok-sqlc";

#[derive(Debug, Default)]
pub struct WriteReport {
    pub written: Vec<PathBuf>,
    pub unchanged: Vec<PathBuf>,
    pub refused: Vec<(PathBuf, String)>,
}

/// Whether `path` is an existing file carrying the rok-sqlc generated header.
pub fn is_generated_file(path: &Path) -> bool {
    fs::read_to_string(path).is_ok_and(|contents| contents.starts_with(GENERATED_MARKER))
}

pub fn apply_files(files: &[(PathBuf, String)], dry_run: bool, force: bool) -> Result<WriteReport> {
    let mut report = WriteReport::default();
    let mut writes: Vec<(&PathBuf, &String)> = Vec::new();

    for (path, contents) in files {
        match classify(path, contents, force)? {
            Action::Write => {
                report.written.push(path.clone());
                writes.push((path, contents));
            }
            Action::Unchanged => report.unchanged.push(path.clone()),
            Action::Refuse(reason) => report.refused.push((path.clone(), reason)),
        }
    }

    if dry_run || !report.refused.is_empty() {
        return Ok(report);
    }

    for (path, contents) in writes {
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)
                .with_context(|| format!("failed to create directory `{}`", parent.display()))?;
        }
        fs::write(path, contents)
            .with_context(|| format!("failed to write `{}`", path.display()))?;
    }

    Ok(report)
}

enum Action {
    Write,
    Unchanged,
    Refuse(String),
}

fn classify(path: &Path, contents: &str, force: bool) -> Result<Action> {
    if !path.exists() {
        return Ok(Action::Write);
    }

    let existing = fs::read_to_string(path)
        .with_context(|| format!("failed to read existing file `{}`", path.display()))?;

    if !existing.starts_with(GENERATED_MARKER) && !force {
        return Ok(Action::Refuse(
            "file exists and was not generated by rok-sqlc; pass --force to overwrite".to_owned(),
        ));
    }

    if existing == contents {
        return Ok(Action::Unchanged);
    }

    Ok(Action::Write)
}

#[cfg(test)]
mod tests {
    use super::*;
    use tempfile::TempDir;

    fn generated_file(contents: &str) -> (PathBuf, String) {
        (
            PathBuf::from("db/mod.rs"),
            format!("// @generated by rok-sqlc. Do not edit by hand.\n{contents}"),
        )
    }

    #[test]
    fn writes_new_files() -> Result<()> {
        let dir = TempDir::new()?;
        let files = vec![(dir.path().join("db/mod.rs"), "pub mod schema;\n".to_owned())];
        let report = apply_files(&files, false, false)?;
        assert_eq!(report.written.len(), 1);
        assert!(report.refused.is_empty());
        assert_eq!(
            fs::read_to_string(dir.path().join("db/mod.rs"))?,
            "pub mod schema;\n"
        );
        Ok(())
    }

    #[test]
    fn regenerates_files_with_generated_header() -> Result<()> {
        let dir = TempDir::new()?;
        let file = dir.path().join("db/mod.rs");
        fs::create_dir_all(file.parent().unwrap())?;
        fs::write(&file, generated_file("pub mod old;\n").1)?;

        let files = vec![(file.clone(), "pub mod new;\n".to_owned())];
        let report = apply_files(&files, false, false)?;
        assert_eq!(report.written.len(), 1);
        assert_eq!(fs::read_to_string(&file)?, "pub mod new;\n");
        Ok(())
    }

    #[test]
    fn refuses_foreign_files_without_force() -> Result<()> {
        let dir = TempDir::new()?;
        let file = dir.path().join("db/mod.rs");
        fs::create_dir_all(file.parent().unwrap())?;
        fs::write(&file, "// hand-written, precious\n")?;

        let files = vec![(file.clone(), "pub mod new;\n".to_owned())];
        let report = apply_files(&files, false, false)?;
        assert_eq!(report.refused.len(), 1);
        assert_eq!(fs::read_to_string(&file)?, "// hand-written, precious\n");

        let report = apply_files(&files, false, true)?;
        assert_eq!(report.written.len(), 1);
        assert_eq!(fs::read_to_string(&file)?, "pub mod new;\n");
        Ok(())
    }

    #[test]
    fn refuses_anything_when_one_file_is_refused() -> Result<()> {
        let dir = TempDir::new()?;
        let guarded = dir.path().join("db/precious.rs");
        fs::create_dir_all(guarded.parent().unwrap())?;
        fs::write(&guarded, "// hand-written\n")?;

        let files = vec![
            (guarded, "x".to_owned()),
            (dir.path().join("db/fresh.rs"), "y".to_owned()),
        ];
        let report = apply_files(&files, false, false)?;
        assert_eq!(report.refused.len(), 1);
        assert!(!dir.path().join("db/fresh.rs").exists());
        Ok(())
    }

    #[test]
    fn dry_run_writes_nothing() -> Result<()> {
        let dir = TempDir::new()?;
        let files = vec![(dir.path().join("db/mod.rs"), "pub mod schema;\n".to_owned())];
        let report = apply_files(&files, true, false)?;
        assert_eq!(report.written.len(), 1);
        assert!(!dir.path().join("db/mod.rs").exists());
        Ok(())
    }

    #[test]
    fn reports_unchanged_files() -> Result<()> {
        let dir = TempDir::new()?;
        let files = vec![(
            dir.path().join("db/mod.rs"),
            generated_file("pub mod schema;\n").1,
        )];
        apply_files(&files, false, false)?;
        let report = apply_files(&files, false, false)?;
        assert_eq!(report.unchanged.len(), 1);
        assert!(report.written.is_empty());
        Ok(())
    }
}
