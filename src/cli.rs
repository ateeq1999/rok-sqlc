//! The `rok-sqlc` command line: parses flags into a [`Config`], calls
//! [`generate`](crate::generate), and prints the [`Report`].

use std::ffi::OsString;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};
use clap::{Parser, Subcommand};

use crate::config_file::{self, FileConfig};
use crate::report::display_path;
use crate::{Config, Derive, Extractor, Report};

#[derive(Debug, Parser)]
#[command(
    name = "rok-sqlc",
    version,
    about = "Generate SQLx Rust modules from SQL schema files"
)]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Debug, Subcommand)]
#[allow(
    clippy::large_enum_variant,
    reason = "parsed once per run; boxing the flags buys nothing"
)]
enum Command {
    /// Generate Rust database modules from a schema file
    #[command(visible_alias = "g")]
    Generate {
        /// Schema/migration SQL file, or a directory of migrations read in
        /// filename order (`*.down.sql` skipped); repeat to combine inputs
        /// [default: `schema` from rok-sqlc.toml]
        #[arg(short, long, value_name = "PATH")]
        schema: Vec<PathBuf>,

        /// Output directory [default: src/db]
        #[arg(short, long, value_name = "DIR")]
        output: Option<PathBuf>,

        /// Generate this table and regenerate those already generated; skip the rest
        #[arg(short, long, value_name = "TABLE")]
        resource: Option<String>,

        /// List planned writes and refusals without touching the filesystem
        #[arg(short = 'n', long)]
        dry_run: bool,

        /// Write nothing; list missing, changed, and stale files and exit 1 if any
        #[arg(short = 'k', long)]
        check: bool,

        /// Overwrite existing files that were not generated by rok-sqlc
        #[arg(short, long)]
        force: bool,

        /// Annotated query file (generates `queries.rs`) or directory (one
        /// `queries/<stem>.rs` module per `.sql` file); repeatable
        #[arg(short, long, value_name = "PATH")]
        queries: Vec<PathBuf>,

        /// Skip unsupported tables and queries with warnings instead of failing
        #[arg(short, long)]
        lenient: bool,

        /// Read options from this config file instead of discovering
        /// rok-sqlc.toml in the current directory or its parents
        #[arg(short, long, value_name = "FILE")]
        config: Option<PathBuf>,

        /// Options as JSON in the shape of rok-sqlc.toml: inline, `@FILE`, or
        /// `-` for stdin; paths resolve against the current directory
        #[arg(short, long, value_name = "JSON|@FILE|-", allow_hyphen_values = true)]
        json: Option<String>,

        /// Also derive this for the generated types: `serde` adds
        /// `Serialize`/`Deserialize`, `validate` adds schema-derived
        /// `validator::Validate` to inputs and patches (needs `serde`);
        /// repeatable [default: `derive` from rok-sqlc.toml]
        #[arg(short, long, value_name = "NAME", value_enum)]
        derive: Vec<DeriveArg>,

        /// Generate a validated-body extractor for this framework into `http/`
        /// (needs `-d validate`); repeatable [default: `extractors` from
        /// rok-sqlc.toml]
        #[arg(short, long, value_name = "FRAMEWORK", value_enum)]
        extractor: Vec<ExtractorArg>,

        /// Generate API features into this directory (needs `-d serde -d
        /// validate` and the framework's extractor: `-e actix_web`, or `-e
        /// axum` with `api.framework = "axum"`) [default: `api.output` from
        /// rok-sqlc.toml]
        #[arg(short, long, value_name = "DIR")]
        api_output: Option<PathBuf>,
    },

    /// Scaffold the application skeleton (ADR 0016), for actix-web or axum,
    /// into a project, each file only if absent; generates nothing
    #[command(visible_alias = "i")]
    Init {
        /// The project directory
        #[arg(value_name = "DIR", default_value = ".")]
        dir: PathBuf,

        /// Copy this ready-made project instead of the skeleton, each file
        /// only if absent, leaving out its generated files
        #[arg(
            short,
            long,
            value_name = "NAME",
            value_parser = clap::builder::PossibleValuesParser::new(crate::init::template_names())
        )]
        template: Option<String>,

        /// The web framework of the skeleton and of the API `rok-sqlc g`
        /// generates (`[api] framework`)
        #[arg(
            short,
            long,
            value_name = "FRAMEWORK",
            value_enum,
            default_value = "actix",
            conflicts_with = "template"
        )]
        framework: FrameworkArg,
    },

    /// Check the project against ADR 0016's architecture: the feature
    /// layout and rules 1, 2, 4, 5 and 6; print each violation as
    /// `path:line: rule: message` and exit 1 if any
    #[command(visible_alias = "a")]
    CheckArch {
        /// Report layout violations as warnings instead of failing
        #[arg(short, long)]
        lenient: bool,

        /// Read `api.output` and `api.db_path` from this config file instead
        /// of discovering rok-sqlc.toml in the current directory or its
        /// parents
        #[arg(short, long, value_name = "FILE")]
        config: Option<PathBuf>,
    },
}

/// The clap definition of the `rok-sqlc` command line.
pub fn command() -> clap::Command {
    <Cli as clap::CommandFactory>::command()
}

pub fn run() -> Result<()> {
    run_from(std::env::args_os())
}

pub fn run_from<I, T>(args: I) -> Result<()>
where
    I: IntoIterator<Item = T>,
    T: Into<OsString> + Clone,
{
    let cli = match Cli::try_parse_from(args) {
        Ok(cli) => cli,
        Err(err) if is_informational(&err) => {
            // `--help` / `--version` are successful outcomes, not errors.
            err.print()?;
            return Ok(());
        }
        Err(err) => return Err(err.into()),
    };
    match cli.command {
        Command::CheckArch { lenient, config } => check_arch(config, lenient),
        Command::Init {
            dir,
            template: Some(template),
            ..
        } => {
            let scaffolded = crate::init::init_template(&dir, &template)?;
            let mut steps = Vec::new();
            if !scaffolded.wrote_manifest {
                steps.push(
                    "add the template's dependencies and lints (its README.md lists them) to Cargo.toml",
                );
            }
            print_scaffolded(scaffolded);
            steps.extend([
                "run `rok-sqlc g` to generate src/db/, src/shared/ and src/features/ from migrations/",
                "set DATABASE_URL and JWT_SECRET (see .env.example) and apply migrations/",
                "`cargo test`, then `cargo run`",
            ]);
            print_next_steps(&steps);
            Ok(())
        }
        Command::Init {
            dir,
            template: None,
            framework,
        } => {
            print_scaffolded(crate::init::init(&dir, framework.into())?);
            print_next_steps(&[
                "add the dependencies listed at the end of rok-sqlc.toml to Cargo.toml",
                "add migrations to migrations/ (0001_init.sql, ...)",
                "run `rok-sqlc g` to generate src/db/ and src/features/",
                "set DATABASE_URL and JWT_SECRET, then `cargo run`",
            ]);
            Ok(())
        }
        Command::Generate {
            schema,
            output,
            resource,
            dry_run,
            check,
            force,
            queries,
            lenient,
            config,
            json,
            derive,
            extractor,
            api_output,
        } => {
            let payload = match json {
                Some(arg) => config_file::load_json(&arg)?,
                None => FileConfig::default(),
            };
            let file = match config {
                Some(path) => config_file::load(&path)?,
                None => match config_file::discover(&std::env::current_dir()?) {
                    Some(path) => config_file::load(&path)?,
                    None => FileConfig::default(),
                },
            };
            let flags = FileConfig {
                schema,
                queries,
                output,
                resource,
                conventions: Default::default(),
                derive: (!derive.is_empty())
                    .then(|| derive.into_iter().map(Derive::from).collect()),
                extractors: (!extractor.is_empty())
                    .then(|| extractor.into_iter().map(Extractor::from).collect()),
                relationships: Default::default(),
                modules: Default::default(),
                api: config_file::ApiKeys::output(api_output),
            };
            // Flags override the JSON payload, which overrides the file,
            // which overrides the defaults. `--schema` and `--queries` (each
            // given any number of times) replace the lower sources' whole
            // `schema` / `queries` list; an empty Vec means "not set".
            let merged = flags.over(payload.over(file));
            if merged.schema.is_empty() {
                return Err(missing_schema().into());
            }
            let defaults = Config::default();
            generate(&Config {
                schema: merged.schema,
                queries: merged.queries,
                output: merged.output.unwrap_or(defaults.output),
                resource: merged.resource,
                dry_run,
                check,
                force,
                lenient,
                conventions: merged.conventions.resolve(),
                derive: merged.derive.unwrap_or_default(),
                extractors: merged.extractors.unwrap_or_default(),
                relationships: merged.relationships,
                modules: merged.modules,
                api: merged.api.resolve(),
            })
        }
    }
}

/// Prints what `init` wrote.
fn print_scaffolded(scaffolded: crate::init::Scaffolded) {
    if scaffolded.replaced_default_main {
        println!("replaced cargo's default src/main.rs");
    }
    for path in scaffolded.written {
        println!("scaffolded {}", display_path(&path));
    }
}

/// Prints `init`'s numbered next steps.
fn print_next_steps(steps: &[&str]) {
    println!("\nNext steps:");
    for (number, step) in steps.iter().enumerate() {
        println!("  {}. {step}", number + 1);
    }
}

/// `check-arch`: checks the project whose config file is `config` (or the
/// discovered `rok-sqlc.toml`), printing violations on stdout and, with
/// `lenient`, layout violations as warnings on stderr.
fn check_arch(config: Option<PathBuf>, lenient: bool) -> Result<()> {
    let path = match config {
        Some(path) => path,
        None => config_file::discover(&std::env::current_dir()?).with_context(|| {
            format!(
                "no {} found in the current directory or its parents",
                config_file::FILE_NAME
            )
        })?,
    };
    let api = config_file::load(&path)?.api.resolve().with_context(|| {
        format!(
            "{} sets no `api.output`: check-arch checks an API project",
            display_path(&path)
        )
    })?;
    let project = crate::check_arch::Project {
        root: path.parent().unwrap_or(Path::new("")).to_path_buf(),
        features: api.output,
        db_path: api.db_path,
        framework: api.framework,
    };
    let mut failures = 0;
    for violation in crate::check_arch::check(&project)? {
        if lenient && violation.rule.is_layout() {
            eprintln!("warning: {violation}");
        } else {
            failures += 1;
            println!("{violation}");
        }
    }
    if failures > 0 {
        bail!("check-arch found {failures} violation(s)");
    }
    Ok(())
}

/// A `--derive` value. It mirrors [`Derive`], which stays free of clap
/// because it is part of the stable library API (ADR 0012).
#[derive(Debug, Clone, Copy, PartialEq, Eq, clap::ValueEnum)]
enum DeriveArg {
    Serde,
    Validate,
}

impl From<DeriveArg> for Derive {
    fn from(arg: DeriveArg) -> Self {
        match arg {
            DeriveArg::Serde => Derive::Serde,
            DeriveArg::Validate => Derive::Validate,
        }
    }
}

/// An `--extractor` value, mirroring [`Extractor`] as [`DeriveArg`]
/// mirrors [`Derive`].
#[derive(Debug, Clone, Copy, PartialEq, Eq, clap::ValueEnum)]
enum ExtractorArg {
    Axum,
    #[value(name = "actix_web")]
    ActixWeb,
}

impl From<ExtractorArg> for Extractor {
    fn from(arg: ExtractorArg) -> Self {
        match arg {
            ExtractorArg::Axum => Extractor::Axum,
            ExtractorArg::ActixWeb => Extractor::ActixWeb,
        }
    }
}

/// An `init --framework` value, mirroring [`crate::ApiFramework`].
#[derive(Debug, Clone, Copy, PartialEq, Eq, clap::ValueEnum)]
enum FrameworkArg {
    Actix,
    Axum,
}

impl From<FrameworkArg> for crate::ApiFramework {
    fn from(arg: FrameworkArg) -> Self {
        match arg {
            FrameworkArg::Actix => crate::ApiFramework::Actix,
            FrameworkArg::Axum => crate::ApiFramework::Axum,
        }
    }
}

/// The usage error for a run with neither `--schema` nor a `schema` key in
/// the JSON payload or the config file.
fn missing_schema() -> clap::Error {
    let mut cmd = command();
    cmd.build();
    let generate = cmd
        .find_subcommand_mut("generate")
        .expect("the generate subcommand exists");
    generate.error(
        clap::error::ErrorKind::MissingRequiredArgument,
        format!(
            "no schema given: pass --schema <PATH>, or set `schema` in the --json payload or {}",
            config_file::FILE_NAME
        ),
    )
}

fn is_informational(err: &clap::Error) -> bool {
    use clap::error::ErrorKind;
    matches!(
        err.kind(),
        ErrorKind::DisplayHelp | ErrorKind::DisplayVersion
    )
}

fn generate(config: &Config) -> Result<()> {
    match crate::generate(config) {
        Ok(report) => {
            print_report(config, &report);
            Ok(())
        }
        Err(err) => {
            print_report(config, err.report());
            Err(err.into())
        }
    }
}

/// Prints what a run did: skipped or fatal tables and queries, and the
/// warnings, on stderr; planned or written files on stdout.
fn print_report(config: &Config, report: &Report) {
    for failure in &report.table_failures {
        if config.lenient {
            eprintln!(
                "warning: {}table `{}` skipped: {}",
                failure.location(),
                failure.table,
                failure.reason
            );
        } else {
            eprintln!("error: {failure}");
        }
    }
    for failure in &report.query_failures {
        if config.lenient {
            eprintln!(
                "warning: {}query `{}` skipped: {}",
                failure.location(),
                failure.query,
                failure.reason
            );
        } else {
            eprintln!("error: {failure}");
        }
    }
    for warning in &report.warnings {
        eprintln!("warning: {warning}");
    }
    for path in &report.written {
        if config.dry_run {
            println!("would write {}", display_path(path));
        } else {
            println!("generated {}", display_path(path));
        }
    }
    for path in &report.scaffolded {
        if config.dry_run {
            println!("would scaffold {}", display_path(path));
        } else {
            println!("scaffolded {}", display_path(path));
        }
    }
    for path in &report.unchanged {
        println!("unchanged {}", display_path(path));
    }
    for path in &report.missing {
        println!("missing {}", display_path(path));
    }
    for path in &report.changed {
        println!("changed {}", display_path(path));
    }
    for path in &report.stale {
        if config.check {
            println!("stale {}", display_path(path));
        } else if config.dry_run {
            println!("would remove {}", display_path(path));
        } else {
            println!("removed {}", display_path(path));
        }
    }
    for refused in &report.refused {
        let (path, reason) = (display_path(&refused.path), &refused.reason);
        if config.dry_run {
            println!("would refuse {path} ({reason})");
        } else {
            eprintln!("error: refused to write {path} ({reason})");
        }
    }
}
