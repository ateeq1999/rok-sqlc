use crate::schema::Table;

use super::{create_input_columns, patch_type, update_input_columns};

pub fn render(table: &Table) -> String {
    let mut output = String::from("// @generated by rok-sqlc. Do not edit by hand.\n\n");
    output.push_str(&format!(
        "#[derive(Debug, Clone, sqlx::FromRow)]\npub struct {} {{\n",
        table.struct_name
    ));

    for column in &table.columns {
        if column.rust_name != column.sql_name {
            output.push_str(&format!("    #[sqlx(rename = \"{}\")]\n", column.sql_name));
        }
        output.push_str(&format!(
            "    pub {}: {},\n",
            column.rust_name, column.rust_type
        ));
    }

    output.push_str("}\n");

    let create_columns = create_input_columns(table);
    if !create_columns.is_empty() {
        output.push_str(&format!(
            "\n#[derive(Debug, Clone)]\npub struct New{} {{\n",
            table.struct_name
        ));
        for column in create_columns {
            let field_type = if column.has_default {
                patch_type(column)
            } else {
                column.rust_type.clone()
            };
            output.push_str(&format!("    pub {}: {},\n", column.rust_name, field_type));
        }
        output.push_str("}\n");
    }

    let update_columns = update_input_columns(table);
    if !table.primary_key.is_empty() && !update_columns.is_empty() {
        output.push_str(&format!(
            "\n#[derive(Debug, Clone)]\npub struct Update{} {{\n",
            table.struct_name
        ));
        for column in update_columns {
            output.push_str(&format!(
                "    pub {}: {},\n",
                column.rust_name,
                patch_type(column)
            ));
        }
        output.push_str("}\n");
    }

    output
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::schema::Column;

    fn table_with(column: Column) -> Table {
        Table {
            sql_name: "users".to_owned(),
            module_name: "users".to_owned(),
            struct_name: "Users".to_owned(),
            columns: vec![column],
            primary_key: Vec::new(),
            foreign_keys: Vec::new(),
        }
    }

    fn plain_column() -> Column {
        Column {
            sql_name: "email".to_owned(),
            rust_name: "email".to_owned(),
            rust_type: "String".to_owned(),
            sqlx_type: "String".to_owned(),
            nullable: false,
            is_primary_key: false,
            has_default: false,
            is_generated: false,
        }
    }

    #[test]
    fn renders_struct_with_from_row() {
        let rendered = render(&table_with(plain_column()));
        assert!(rendered.contains("#[derive(Debug, Clone, sqlx::FromRow)]"));
        assert!(rendered.contains("pub struct Users {"));
        assert!(rendered.contains("    pub email: String,\n"));
        assert!(rendered.contains("// @generated by rok-sqlc. Do not edit by hand."));
    }

    #[test]
    fn wraps_nullable_columns_in_option() {
        let mut column = plain_column();
        column.rust_type = "Option<String>".to_owned();
        let rendered = render(&table_with(column));
        assert!(rendered.contains("pub email: Option<String>,"));
    }

    #[test]
    fn emits_rename_for_renamed_fields() {
        let mut column = plain_column();
        column.sql_name = "type".to_owned();
        column.rust_name = "type_".to_owned();
        let rendered = render(&table_with(column));
        assert!(rendered.contains("    #[sqlx(rename = \"type\")]\n    pub type_: String,"));
    }

    #[test]
    fn output_is_deterministic() {
        let first = render(&table_with(plain_column()));
        let second = render(&table_with(plain_column()));
        assert_eq!(first, second);
    }

    fn model_table(columns: Vec<Column>, primary_key: Vec<String>) -> Table {
        Table {
            sql_name: "users".to_owned(),
            module_name: "users".to_owned(),
            struct_name: "Users".to_owned(),
            columns,
            primary_key,
            foreign_keys: Vec::new(),
        }
    }

    #[test]
    fn renders_create_input_with_optional_defaulted_columns() {
        let mut id = plain_column();
        id.sql_name = "id".to_owned();
        id.rust_name = "id".to_owned();
        id.rust_type = "i64".to_owned();
        id.is_primary_key = true;
        id.is_generated = true;
        id.has_default = true;
        let mut created_at = plain_column();
        created_at.sql_name = "created_at".to_owned();
        created_at.rust_name = "created_at".to_owned();
        created_at.rust_type = "chrono::DateTime<chrono::Utc>".to_owned();
        created_at.has_default = true;
        let rendered = render(&model_table(
            vec![id, plain_column(), created_at],
            vec!["id".to_owned()],
        ));
        assert!(rendered.contains("pub struct NewUsers {"));
        assert!(rendered.contains("    pub email: String,\n"));
        assert!(rendered.contains("    pub created_at: Option<chrono::DateTime<chrono::Utc>>,\n"));
        let create_block = rendered.split("pub struct NewUsers {").nth(1).unwrap();
        let create_block = create_block.split('}').next().unwrap();
        assert!(!create_block.contains("pub id:"));
    }

    #[test]
    fn renders_update_input_with_nested_option_for_nullable_columns() {
        let mut email = plain_column();
        email.sql_name = "email".to_owned();
        email.rust_name = "email".to_owned();
        let mut note = plain_column();
        note.sql_name = "note".to_owned();
        note.rust_name = "note".to_owned();
        note.rust_type = "Option<String>".to_owned();
        note.nullable = true;
        let rendered = render(&model_table(vec![email, note], vec!["id".to_owned()]));
        assert!(rendered.contains("pub struct UpdateUsers {"));
        assert!(rendered.contains("    pub email: Option<String>,\n"));
        assert!(rendered.contains("    pub note: Option<Option<String>>,\n"));
    }

    #[test]
    fn omits_update_input_without_primary_key() {
        let rendered = render(&table_with(plain_column()));
        assert!(!rendered.contains("pub struct UpdateUsers"));
    }
}
