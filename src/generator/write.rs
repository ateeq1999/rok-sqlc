use crate::schema::Table;

use super::read::{column_list, primary_key_columns};
use super::{create_input_columns, rust_string_literal, update_input_columns};

pub fn render(table: &Table) -> String {
    let mut output = String::from("// @generated by rok-sqlc. Do not edit by hand.\n\n");
    output.push_str("use sqlx::PgPool;\n\n");

    let create_columns = create_input_columns(table);
    let update_columns = update_input_columns(table);
    let pk_columns = primary_key_columns(table);

    let mut imports = vec![table.struct_name.clone()];
    if !create_columns.is_empty() {
        imports.push(format!("New{}", table.struct_name));
    }
    if !pk_columns.is_empty() && !update_columns.is_empty() {
        imports.push(format!("Update{}", table.struct_name));
    }
    output.push_str(&format!(
        "use super::models::{{{}}};\n\n",
        imports.join(", ")
    ));

    render_create(&mut output, table, &create_columns);

    if pk_columns.is_empty() {
        output.push_str(
            "// No primary key detected; update and delete are not generated for this table.\n",
        );
        return output;
    }

    render_update(&mut output, table, &pk_columns, &update_columns);
    render_delete(&mut output, table, &pk_columns);

    output
}

fn render_create(output: &mut String, table: &Table, create_columns: &[&crate::schema::Column]) {
    if create_columns.is_empty() {
        output.push_str(
            "// No insertable columns detected; create is not generated for this table.\n\n",
        );
        return;
    }

    output.push_str(&format!(
        "pub async fn create(pool: &PgPool, input: New{}) -> Result<{}, sqlx::Error> {{\n",
        table.struct_name, table.struct_name
    ));
    output.push_str("    let mut columns: Vec<&str> = Vec::new();\n");
    output.push_str("    let mut placeholders: Vec<String> = Vec::new();\n");
    for column in create_columns {
        let quoted = rust_string_literal(&format!("\"{}\"", column.sql_name));
        if column.has_default {
            output.push_str(&format!("    if input.{}.is_some() {{\n", column.rust_name));
            output.push_str(&format!("        columns.push({quoted});\n"));
            output.push_str("        placeholders.push(format!(\"${}\", columns.len()));\n");
            output.push_str("    }\n");
        } else {
            output.push_str(&format!("    columns.push({quoted});\n"));
            output.push_str("    placeholders.push(format!(\"${}\", columns.len()));\n");
        }
    }

    let table_literal = rust_string_literal(&format!("\"{}\"", table.sql_name));
    let returning = rust_string_literal(&column_list(table));
    let can_be_empty = create_columns.iter().any(|column| column.has_default);

    if can_be_empty {
        output.push_str("    let sql = if columns.is_empty() {\n");
        output.push_str("        format!(\n");
        output.push_str("            \"INSERT INTO {} DEFAULT VALUES RETURNING {}\",\n");
        output.push_str(&format!("            {table_literal},\n"));
        output.push_str(&format!("            {returning}\n"));
        output.push_str("        )\n");
        output.push_str("    } else {\n");
        output.push_str("        format!(\n");
    } else {
        output.push_str("    let sql = format!(\n");
    }

    output.push_str("        \"INSERT INTO {} ({}) VALUES ({}) RETURNING {}\",\n");
    output.push_str(&format!("        {table_literal},\n"));
    output.push_str("        columns.join(\", \"),\n");
    output.push_str("        placeholders.join(\", \"),\n");
    output.push_str(&format!("        {returning}\n"));
    if can_be_empty {
        output.push_str("        )\n");
        output.push_str("    };\n");
    } else {
        output.push_str("    );\n");
    }

    output.push_str(&format!(
        "    let mut query = sqlx::query_as::<_, {}>(&sql);\n",
        table.struct_name
    ));
    for column in create_columns {
        if column.has_default {
            output.push_str(&format!(
                "    if let Some(value) = &input.{} {{\n",
                column.rust_name
            ));
            output.push_str("        query = query.bind(value);\n");
            output.push_str("    }\n");
        } else {
            output.push_str(&format!(
                "    query = query.bind(&input.{});\n",
                column.rust_name
            ));
        }
    }
    output.push_str("    query.fetch_one(pool).await\n");
    output.push_str("}\n\n");
}

fn render_update(
    output: &mut String,
    table: &Table,
    pk_columns: &[&crate::schema::Column],
    update_columns: &[&crate::schema::Column],
) {
    if update_columns.is_empty() {
        output.push_str(
            "// No updatable columns detected; update is not generated for this table.\n\n",
        );
        return;
    }

    let parameters = parameter_list(pk_columns);
    output.push_str(&format!(
        "pub async fn update(pool: &PgPool, {parameters}, input: Update{}) -> Result<Option<{}>, sqlx::Error> {{\n",
        table.struct_name, table.struct_name
    ));
    output.push_str("    let mut sets: Vec<String> = Vec::new();\n");
    for column in update_columns {
        let quoted = rust_string_literal(&format!("\"{}\"", column.sql_name));
        output.push_str(&format!("    if input.{}.is_some() {{\n", column.rust_name));
        output.push_str(&format!(
            "        sets.push(format!(\"{{}} = ${{}}\", {quoted}, sets.len() + 1));\n"
        ));
        output.push_str("    }\n");
    }

    let key_arguments = pk_columns
        .iter()
        .map(|column| column.rust_name.clone())
        .collect::<Vec<_>>()
        .join(", ");
    output.push_str("    if sets.is_empty() {\n");
    output.push_str(&format!(
        "        return super::read::get_by_id(pool, {key_arguments}).await;\n"
    ));
    output.push_str("    }\n");

    output.push_str("    let mut conditions: Vec<String> = Vec::new();\n");
    for (index, column) in pk_columns.iter().enumerate() {
        let quoted = rust_string_literal(&format!("\"{}\"", column.sql_name));
        let offset = index + 1;
        output.push_str(&format!(
            "    conditions.push(format!(\"{{}} = ${{}}\", {quoted}, sets.len() + {offset}));\n"
        ));
    }

    output.push_str("    let sql = format!(\n");
    output.push_str("        \"UPDATE {} SET {} WHERE {} RETURNING {}\",\n");
    output.push_str(&format!(
        "        {},\n",
        rust_string_literal(&format!("\"{}\"", table.sql_name))
    ));
    output.push_str("        sets.join(\", \"),\n");
    output.push_str("        conditions.join(\" AND \"),\n");
    output.push_str(&format!(
        "        {}\n",
        rust_string_literal(&column_list(table))
    ));
    output.push_str("    );\n");

    output.push_str(&format!(
        "    let mut query = sqlx::query_as::<_, {}>(&sql);\n",
        table.struct_name
    ));
    for column in update_columns {
        output.push_str(&format!(
            "    if let Some(value) = &input.{} {{\n",
            column.rust_name
        ));
        output.push_str("        query = query.bind(value);\n");
        output.push_str("    }\n");
    }
    for column in pk_columns {
        output.push_str(&format!("    query = query.bind({});\n", column.rust_name));
    }
    output.push_str("    query.fetch_optional(pool).await\n");
    output.push_str("}\n\n");
}

fn render_delete(output: &mut String, table: &Table, pk_columns: &[&crate::schema::Column]) {
    let parameters = parameter_list(pk_columns);
    output.push_str(&format!(
        "pub async fn delete(pool: &PgPool, {parameters}) -> Result<bool, sqlx::Error> {{\n"
    ));
    let conditions = pk_columns
        .iter()
        .enumerate()
        .map(|(index, column)| format!("\"{}\" = ${}", column.sql_name, index + 1))
        .collect::<Vec<_>>()
        .join(" AND ");
    let sql = format!("DELETE FROM \"{}\" WHERE {}", table.sql_name, conditions);
    output.push_str(&format!(
        "    let result = sqlx::query({})\n",
        rust_string_literal(&sql)
    ));
    for column in pk_columns {
        output.push_str(&format!("        .bind({})\n", column.rust_name));
    }
    output.push_str("        .execute(pool)\n");
    output.push_str("        .await?;\n");
    output.push_str("    Ok(result.rows_affected() > 0)\n");
    output.push_str("}\n");
}

fn parameter_list(pk_columns: &[&crate::schema::Column]) -> String {
    pk_columns
        .iter()
        .map(|column| format!("{}: {}", column.rust_name, column.sqlx_type))
        .collect::<Vec<_>>()
        .join(", ")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::schema::Column;

    fn column(sql_name: &str, sqlx_type: &str) -> Column {
        Column {
            sql_name: sql_name.to_owned(),
            rust_name: sql_name.to_owned(),
            rust_type: sqlx_type.to_owned(),
            sqlx_type: sqlx_type.to_owned(),
            nullable: false,
            is_primary_key: false,
            has_default: false,
            is_generated: false,
        }
    }

    fn table(columns: Vec<Column>, primary_key: Vec<String>) -> Table {
        Table {
            sql_name: "users".to_owned(),
            module_name: "users".to_owned(),
            struct_name: "Users".to_owned(),
            columns,
            primary_key,
            foreign_keys: Vec::new(),
        }
    }

    #[test]
    fn renders_create_with_required_and_defaulted_columns() {
        let mut id = column("id", "uuid::Uuid");
        id.is_primary_key = true;
        id.has_default = true;
        let mut created_at = column("created_at", "chrono::DateTime<chrono::Utc>");
        created_at.has_default = true;
        let rendered = render(&table(
            vec![id, column("email", "String"), created_at],
            vec!["id".to_owned()],
        ));

        assert!(rendered.contains("use super::models::{Users, NewUsers, UpdateUsers};"));
        assert!(rendered.contains("pub async fn create(pool: &PgPool, input: NewUsers)"));
        assert!(rendered.contains("columns.push(\"\\\"email\\\"\");"));
        assert!(rendered.contains("if input.id.is_some() {"));
        assert!(rendered.contains("if input.created_at.is_some() {"));
        assert!(rendered.contains("query = query.bind(&input.email);"));
        assert!(rendered.contains("if let Some(value) = &input.id {"));
        assert!(rendered.contains("\"INSERT INTO {} ({}) VALUES ({}) RETURNING {}\""));
        assert!(rendered.contains("\\\"id\\\", \\\"email\\\", \\\"created_at\\\""));
        assert!(rendered.contains("query.fetch_one(pool).await"));
    }

    #[test]
    fn omits_generated_columns_from_create() {
        let mut id = column("id", "i64");
        id.is_primary_key = true;
        id.is_generated = true;
        id.has_default = true;
        let rendered = render(&table(
            vec![id, column("email", "String")],
            vec!["id".to_owned()],
        ));
        assert!(!rendered.contains("columns.push(\"\\\"id\\\"\")"));
        assert!(!rendered.contains("&input.id"));
    }

    #[test]
    fn renders_update_with_composite_key_and_empty_guard() {
        let mut order_id = column("order_id", "uuid::Uuid");
        order_id.is_primary_key = true;
        let mut product_id = column("product_id", "uuid::Uuid");
        product_id.is_primary_key = true;
        let rendered = render(&table(
            vec![order_id, product_id, column("quantity", "i32")],
            vec!["order_id".to_owned(), "product_id".to_owned()],
        ));

        assert!(rendered.contains(
            "pub async fn update(pool: &PgPool, order_id: uuid::Uuid, product_id: uuid::Uuid, input: UpdateUsers)"
        ));
        assert!(rendered.contains("if input.quantity.is_some() {"));
        assert!(rendered.contains("sets.len() + 1"));
        assert!(rendered.contains("sets.len() + 2"));
        assert!(
            rendered.contains("return super::read::get_by_id(pool, order_id, product_id).await;")
        );
        assert!(rendered.contains(
            "let result = sqlx::query(\"DELETE FROM \\\"users\\\" WHERE \\\"order_id\\\" = $1 AND \\\"product_id\\\" = $2\")"
        ));
        assert!(rendered.contains("Ok(result.rows_affected() > 0)"));
    }

    #[test]
    fn omits_update_and_delete_without_primary_key() {
        let rendered = render(&table(vec![column("email", "String")], Vec::new()));
        assert!(!rendered.contains("pub async fn update"));
        assert!(!rendered.contains("pub async fn delete"));
        assert!(rendered.contains("No primary key detected"));
    }

    #[test]
    fn omits_create_when_all_columns_generated() {
        let mut id = column("id", "i64");
        id.is_primary_key = true;
        id.is_generated = true;
        id.has_default = true;
        let rendered = render(&table(vec![id], vec!["id".to_owned()]));
        assert!(!rendered.contains("pub async fn create"));
        assert!(!rendered.contains("pub struct"));
        assert!(rendered.contains("No insertable columns detected"));
        assert!(rendered.contains("pub async fn delete"));
    }

    #[test]
    fn emits_default_values_fallback_when_all_columns_optional() {
        let mut id = column("id", "i64");
        id.is_primary_key = true;
        id.is_generated = true;
        id.has_default = true;
        let mut created_at = column("created_at", "chrono::DateTime<chrono::Utc>");
        created_at.has_default = true;
        let rendered = render(&table(vec![id, created_at], vec!["id".to_owned()]));
        assert!(rendered.contains("let sql = if columns.is_empty() {"));
        assert!(rendered.contains("\"INSERT INTO {} DEFAULT VALUES RETURNING {}\""));
        assert!(rendered.contains("} else {"));
    }

    #[test]
    fn output_is_deterministic() {
        let build = || {
            render(&table(
                vec![column("id", "i64"), column("email", "String")],
                vec!["id".to_owned()],
            ))
        };
        assert_eq!(build(), build());
    }
}
