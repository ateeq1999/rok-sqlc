use crate::schema::{Column, Table};

pub fn render(table: &Table) -> String {
    let mut output = String::from("// @generated by rok-sqlc. Do not edit by hand.\n\n");
    output.push_str("use sqlx::PgPool;\n\n");
    output.push_str(&format!("use super::models::{};\n\n", table.struct_name));

    if let Some(pk) = primary_key_column(table) {
        let sql = format!(
            "SELECT {} FROM \"{}\" WHERE \"{}\" = $1",
            column_list(table),
            table.sql_name,
            pk.sql_name
        );
        output.push_str(&format!(
            "pub async fn get_by_id(pool: &PgPool, id: {}) -> Result<Option<{}>, sqlx::Error> {{\n",
            pk.sqlx_type, table.struct_name
        ));
        output.push_str(&format!(
            "    sqlx::query_as::<_, {}>({})\n",
            table.struct_name,
            rust_string_literal(&sql)
        ));
        output.push_str("        .bind(id)\n");
        output.push_str("        .fetch_optional(pool)\n");
        output.push_str("        .await\n");
        output.push_str("}\n\n");
    } else {
        output
            .push_str("// No primary key detected; get_by_id is not generated for this table.\n\n");
    }

    let list_sql = format!("SELECT {} FROM \"{}\"", column_list(table), table.sql_name);
    output.push_str(&format!(
        "pub async fn list(pool: &PgPool) -> Result<Vec<{}>, sqlx::Error> {{\n",
        table.struct_name
    ));
    output.push_str(&format!(
        "    sqlx::query_as::<_, {}>({})\n",
        table.struct_name,
        rust_string_literal(&list_sql)
    ));
    output.push_str("        .fetch_all(pool)\n");
    output.push_str("        .await\n");
    output.push_str("}\n");

    output
}

fn rust_string_literal(value: &str) -> String {
    let mut literal = String::with_capacity(value.len() + 2);
    literal.push('"');
    for character in value.chars() {
        match character {
            '"' => literal.push_str("\\\""),
            '\\' => literal.push_str("\\\\"),
            _ => literal.push(character),
        }
    }
    literal.push('"');
    literal
}

fn primary_key_column(table: &Table) -> Option<&Column> {
    let pk = table.primary_key.as_deref()?;
    table.columns.iter().find(|column| column.sql_name == pk)
}

fn column_list(table: &Table) -> String {
    table
        .columns
        .iter()
        .map(|column| format!("\"{}\"", column.sql_name))
        .collect::<Vec<_>>()
        .join(", ")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::schema::Column;

    fn column(sql_name: &str, sqlx_type: &str, pk: bool) -> Column {
        Column {
            sql_name: sql_name.to_owned(),
            rust_name: sql_name.to_owned(),
            rust_type: sqlx_type.to_owned(),
            sqlx_type: sqlx_type.to_owned(),
            nullable: false,
            is_primary_key: pk,
        }
    }

    fn table(columns: Vec<Column>, primary_key: Option<String>) -> Table {
        Table {
            sql_name: "users".to_owned(),
            module_name: "users".to_owned(),
            struct_name: "Users".to_owned(),
            columns,
            primary_key,
            foreign_keys: Vec::new(),
        }
    }

    #[test]
    fn renders_get_by_id_and_list_with_quoted_columns() {
        let rendered = render(&table(
            vec![column("id", "i64", true), column("email", "String", false)],
            Some("id".to_owned()),
        ));
        assert!(rendered.contains("pub async fn get_by_id(pool: &PgPool, id: i64)"));
        assert!(
            rendered.contains(
                "SELECT \\\"id\\\", \\\"email\\\" FROM \\\"users\\\" WHERE \\\"id\\\" = $1"
            )
        );
        assert!(rendered.contains("pub async fn list(pool: &PgPool)"));
        assert!(rendered.contains("SELECT \\\"id\\\", \\\"email\\\" FROM \\\"users\\\""));
        assert!(rendered.contains(".fetch_optional(pool)"));
        assert!(rendered.contains(".fetch_all(pool)"));
    }

    #[test]
    fn escapes_quotes_in_generated_sql_literals() {
        assert_eq!(
            rust_string_literal("SELECT \"a\" FROM \"t\""),
            "\"SELECT \\\"a\\\" FROM \\\"t\\\"\""
        );
        assert_eq!(rust_string_literal("back\\slash"), "\"back\\\\slash\"");
    }

    #[test]
    fn omits_get_by_id_without_primary_key() {
        let rendered = render(&table(vec![column("email", "String", false)], None));
        assert!(!rendered.contains("pub async fn get_by_id"));
        assert!(rendered.contains("No primary key detected"));
        assert!(rendered.contains("pub async fn list(pool: &PgPool)"));
    }

    #[test]
    fn output_is_deterministic() {
        let first = render(&table(
            vec![column("id", "i64", true)],
            Some("id".to_owned()),
        ));
        let second = render(&table(
            vec![column("id", "i64", true)],
            Some("id".to_owned()),
        ));
        assert_eq!(first, second);
    }
}
