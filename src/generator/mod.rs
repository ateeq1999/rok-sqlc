pub mod models;
pub mod read;
pub mod write;

use std::path::{Path, PathBuf};

use crate::schema::{Column, Table};

pub fn plan_files(schema_sql: &str, tables: &[Table], output: &Path) -> Vec<(PathBuf, String)> {
    let mut files = Vec::new();

    for table in tables {
        let dir = output.join(&table.module_name);
        files.push((dir.join("mod.rs"), render_resource_mod()));
        files.push((dir.join("models.rs"), models::render(table)));
        files.push((dir.join("read.rs"), read::render(table)));
        files.push((dir.join("write.rs"), write::render(table)));
    }

    files.push((output.join("mod.rs"), render_db_mod(tables)));
    files.push((output.join("schema.rs"), render_schema_snapshot(schema_sql)));

    files
}

fn render_resource_mod() -> String {
    "// @generated by rok-sqlc. Do not edit by hand.\n\npub mod models;\npub mod read;\npub mod write;\n"
        .to_owned()
}

/// Columns the client supplies on insert: every column the database does not
/// generate itself.
pub fn create_input_columns(table: &Table) -> Vec<&Column> {
    table
        .columns
        .iter()
        .filter(|column| !column.is_generated)
        .collect()
}

/// Columns the client may change on update: every column that is neither
/// database-generated nor part of the primary key.
pub fn update_input_columns(table: &Table) -> Vec<&Column> {
    table
        .columns
        .iter()
        .filter(|column| !column.is_generated && !column.is_primary_key)
        .collect()
}

/// The patch/optional form of a column type: nullable columns become
/// `Option<Option<T>>` so "leave unchanged" is distinct from "set NULL".
pub fn patch_type(column: &Column) -> String {
    format!("Option<{}>", column.rust_type)
}

/// Builds a generated query-function signature: the given head, followed by the
/// generic executor bound shared by every generated function.
pub fn executor_signature(head: &str) -> String {
    format!("{head}\nwhere\n    E: sqlx::PgExecutor<'e>,\n{{\n")
}

pub fn rust_string_literal(value: &str) -> String {
    let mut literal = String::with_capacity(value.len() + 2);
    literal.push('"');
    for character in value.chars() {
        match character {
            '"' => literal.push_str("\\\""),
            '\\' => literal.push_str("\\\\"),
            _ => literal.push(character),
        }
    }
    literal.push('"');
    literal
}

pub fn render_db_mod(tables: &[Table]) -> String {
    let mut output = String::from("// @generated by rok-sqlc. Do not edit by hand.\n\n");
    output.push_str("// The generated code requires these dependencies in the consuming crate:\n");
    output.push_str(&dependency_hints(tables));
    output.push_str("\npub mod schema;\n");
    for table in tables {
        output.push_str(&format!("pub mod {};\n", table.module_name));
    }
    output
}

fn dependency_hints(tables: &[Table]) -> String {
    let mut uses_uuid = false;
    let mut uses_chrono = false;
    let mut uses_serde_json = false;
    let mut uses_rust_decimal = false;

    for table in tables {
        for column in &table.columns {
            if column.rust_type.contains("uuid::") {
                uses_uuid = true;
            }
            if column.rust_type.contains("chrono::") {
                uses_chrono = true;
            }
            if column.rust_type.contains("serde_json::") {
                uses_serde_json = true;
            }
            if column.rust_type.contains("rust_decimal::") {
                uses_rust_decimal = true;
            }
        }
    }

    let mut features = String::from("\"runtime-tokio\", \"postgres\", \"derive\"");
    if uses_uuid {
        features.push_str(", \"uuid\"");
    }
    if uses_chrono {
        features.push_str(", \"chrono\"");
    }
    if uses_serde_json {
        features.push_str(", \"json\"");
    }
    if uses_rust_decimal {
        features.push_str(", \"rust_decimal\"");
    }

    let mut hints = format!("//   sqlx = {{ version = \"0.8\", features = [{features}] }}\n");
    if uses_uuid {
        hints.push_str("//   uuid = \"1\"\n");
    }
    if uses_chrono {
        hints.push_str("//   chrono = \"0.4\"\n");
    }
    if uses_serde_json {
        hints.push_str("//   serde_json = \"1\"\n");
    }
    if uses_rust_decimal {
        hints.push_str("//   rust_decimal = \"1\"\n");
    }
    hints
}

pub fn render_schema_snapshot(schema_sql: &str) -> String {
    let mut depth = 1;
    while schema_sql.contains(&format!("\"{}", "#".repeat(depth))) {
        depth += 1;
    }
    let hashes = "#".repeat(depth);
    format!(
        "// @generated by rok-sqlc. Do not edit by hand.\n// Verbatim snapshot of the input schema; never executed.\n\npub const SCHEMA_SQL: &str = r{hashes}\"{schema_sql}\"{hashes};\n"
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample_table(rust_type: &str) -> Table {
        Table {
            sql_name: "users".to_owned(),
            module_name: "users".to_owned(),
            struct_name: "Users".to_owned(),
            columns: vec![crate::schema::Column {
                sql_name: "id".to_owned(),
                rust_name: "id".to_owned(),
                rust_type: rust_type.to_owned(),
                sqlx_type: rust_type.to_owned(),
                nullable: false,
                is_primary_key: true,
                has_default: false,
                is_generated: false,
            }],
            primary_key: vec!["id".to_owned()],
            foreign_keys: Vec::new(),
        }
    }

    #[test]
    fn plans_resource_and_root_files() {
        let tables = vec![sample_table("i64")];
        let files = plan_files("CREATE TABLE users (id BIGINT);", &tables, Path::new("out"));

        let paths: Vec<_> = files.iter().map(|(p, _)| p.clone()).collect();
        assert!(paths.contains(&Path::new("out").join("users").join("mod.rs")));
        assert!(paths.contains(&Path::new("out").join("users").join("models.rs")));
        assert!(paths.contains(&Path::new("out").join("users").join("read.rs")));
        assert!(paths.contains(&Path::new("out").join("users").join("write.rs")));
        assert!(paths.contains(&Path::new("out").join("mod.rs")));
        assert!(paths.contains(&Path::new("out").join("schema.rs")));
    }

    #[test]
    fn db_mod_lists_modules_and_conditional_dependencies() {
        let tables = vec![sample_table("uuid::Uuid")];
        let rendered = render_db_mod(&tables);
        assert!(rendered.contains("pub mod users;"));
        assert!(rendered.contains("pub mod schema;"));
        assert!(rendered.contains("\"uuid\""));
        assert!(!rendered.contains("\"chrono\""));
        assert!(rendered.contains("uuid = \"1\""));
    }

    #[test]
    fn db_mod_hints_rust_decimal_when_used() {
        let tables = vec![sample_table("rust_decimal::Decimal")];
        let rendered = render_db_mod(&tables);
        assert!(rendered.contains("\"rust_decimal\""));
        assert!(rendered.contains("rust_decimal = \"1\""));
        assert!(!rendered.contains("\"uuid\""));
    }

    #[test]
    fn snapshot_escapes_raw_string_delimiters() {
        let schema = "CREATE TABLE tricky (x TEXT, marker TEXT); -- contains \"# inside\n";
        let rendered = render_schema_snapshot(schema);
        assert!(rendered.contains("r##\""));
        assert!(rendered.ends_with("\"##;\n"));
        assert!(rendered.contains(schema));
    }

    #[test]
    fn snapshot_uses_single_hash_when_safe() {
        let rendered = render_schema_snapshot("CREATE TABLE plain (x TEXT);\n");
        assert!(rendered.contains("r#\""));
        assert!(rendered.ends_with("\"#;\n"));
    }

    #[test]
    fn generated_query_functions_use_generic_executor_not_concrete_pool() {
        let table = sample_table("i64");
        for rendered in [read::render(&table), write::render(&table)] {
            assert!(rendered.contains("E: sqlx::PgExecutor<'e>,"));
            assert!(!rendered.contains("PgPool"));
            assert!(!rendered.contains("PgConnection"));
        }
    }

    #[test]
    fn executor_signature_appends_shared_bound() {
        assert_eq!(
            executor_signature("pub async fn list<'e, E>(executor: E) -> Result<(), sqlx::Error>"),
            "pub async fn list<'e, E>(executor: E) -> Result<(), sqlx::Error>\nwhere\n    E: sqlx::PgExecutor<'e>,\n{\n"
        );
    }

    #[test]
    fn output_is_deterministic() {
        let tables = vec![sample_table("i64")];
        let first = plan_files("CREATE TABLE users (id BIGINT);", &tables, Path::new("out"));
        let second = plan_files("CREATE TABLE users (id BIGINT);", &tables, Path::new("out"));
        assert_eq!(first, second);
    }
}
