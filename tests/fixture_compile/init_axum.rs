/// `tests/docs.rs` of the project: the scaffolded router, served on a
/// local port, answers `/health/live`, the document with the generated
/// paths, and Swagger UI. The pool never connects.
const DOCS_TEST: &str = r#"//! The document, Swagger UI and health the scaffolded router serves.

use std::io::{Read, Write};

use init_axum_e2e::app::{AppState, router};
use init_axum_e2e::shared::auth::JwtKeys;

/// `GET path` on `addr`, answered whole.
fn get(addr: std::net::SocketAddr, path: &str) -> std::io::Result<String> {
    let mut stream = std::net::TcpStream::connect(addr)?;
    write!(stream, "GET {path} HTTP/1.1\r\nHost: localhost\r\nConnection: close\r\n\r\n")?;
    let mut answer = String::new();
    stream.read_to_string(&mut answer)?;
    Ok(answer)
}

#[tokio::test(flavor = "multi_thread")]
async fn serves_the_document_swagger_ui_and_health() -> Result<(), Box<dyn std::error::Error>> {
    let pool = sqlx::PgPool::connect_lazy("postgres://localhost/unused")?;
    let state = AppState::new(pool, JwtKeys::new("unused"));
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await?;
    let addr = listener.local_addr()?;
    tokio::spawn(async move { axum::serve(listener, router(state)).await });
    let answers = tokio::task::spawn_blocking(move || {
        ["/api-docs/openapi.json", "/docs/", "/health/live", "/api/v1/notes/not-a-uuid"]
            .map(|path| get(addr, path).map_err(|error| error.to_string()))
    })
    .await?;
    let [document, docs, live, bad] = answers;
    let document = document?;
    assert!(document.starts_with("HTTP/1.1 200"), "{document}");
    assert!(document.contains("\"/api/v1/notes/{id}\""), "{document}");
    assert!(document.contains("\"bearer_auth\""), "{document}");
    let docs = docs?;
    assert!(docs.starts_with("HTTP/1.1 200"), "{docs}");
    let live = live?;
    assert!(live.contains("{\"status\":\"ok\"}"), "{live}");
    assert!(live.contains("x-request-id"), "{live}");
    let bad = bad?;
    assert!(bad.starts_with("HTTP/1.1 400"), "{bad}");
    assert!(bad.contains("\"code\":\"bad_request\""), "{bad}");
    Ok(())
}
"#;

/// The project `rok-sqlc init --framework axum` scaffolds, generated by
/// `rok-sqlc g` from [`MIGRATION`]: it obeys `check-arch`, passes `cargo
/// clippy --all-targets -- -D warnings` with exactly the hinted
/// dependencies, and serves its document, Swagger UI and health.
#[test]
fn init_axum_then_generate_builds_end_to_end() -> Result<()> {
    let fixture = api_app_axum_dir();
    if let Some(reason) = common::generated_code_skip_reason(&fixture) {
        eprintln!("{reason}");
        return Ok(());
    }
    let project = tempfile::TempDir::new()?;
    let dir = project.path();
    let name = "init-axum-e2e";
    std::fs::write(
        dir.join("Cargo.toml"),
        format!("[package]\nname = \"{name}\"\nversion = \"0.1.0\"\nedition = \"2024\"\n"),
    )?;
    rok_sqlc(dir, &["init", "--framework", "axum"])?;
    std::fs::write(dir.join("migrations/0001_init.sql"), MIGRATION)?;
    edit(&dir.join("rok-sqlc.toml"), SETTINGS)?;
    rok_sqlc(dir, &["g"])?;
    rok_sqlc(dir, &["check-arch"])?;
    let manifest = write_manifest_for(dir, name, &[], "axum", &fixture)?;
    std::fs::create_dir_all(dir.join("tests"))?;
    std::fs::write(dir.join("tests/docs.rs"), DOCS_TEST)?;

    ensure_clippy_clean(dir, &manifest)?;
    let output = cargo(dir, &["test", "--quiet", "--test", "docs"])
        .output()
        .context("failed to run cargo test")?;
    ensure!(
        output.status.success(),
        "the axum project `init` and `g` made doesn't serve its docs:\n{}{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
    Ok(())
}

/// Replaces in the file at `path` each `(from, to)`, which must match.
fn edit(path: &Path, edits: &[(&str, &str)]) -> Result<()> {
    let mut text = std::fs::read_to_string(path)?;
    for (from, to) in edits {
        ensure!(text.contains(from), "{} has no {from:?}", path.display());
        text = text.replacen(from, to, 1);
    }
    std::fs::write(path, text)?;
    Ok(())
}
