/// Every shape the axum edge renders: an admin, versioned table with a
/// `by-` route and many `notes`; public, soft-deleted `notes` embedding
/// their account and paired with `tags`; owned, tenant-scoped `tasks`; and
/// a composite text key.
const MIGRATION: &str = "CREATE TABLE accounts (
    id UUID PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    revision INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE notes (
    id UUID PRIMARY KEY,
    account_id UUID NOT NULL REFERENCES accounts (id),
    title TEXT NOT NULL CHECK (char_length(title) <= 120),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ
);
CREATE TABLE tags (id UUID PRIMARY KEY, name TEXT NOT NULL);
CREATE TABLE note_tags (
    note_id UUID NOT NULL REFERENCES notes (id),
    tag_id UUID NOT NULL REFERENCES tags (id),
    PRIMARY KEY (note_id, tag_id)
);
CREATE TABLE tasks (
    id UUID PRIMARY KEY,
    tenant_id UUID NOT NULL,
    owner_id UUID NOT NULL,
    title TEXT NOT NULL
);
CREATE TABLE memberships (
    org TEXT NOT NULL,
    email TEXT NOT NULL,
    role TEXT,
    PRIMARY KEY (org, email)
);
";

